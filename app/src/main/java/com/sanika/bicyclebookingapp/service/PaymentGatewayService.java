package com.sanika.bicyclebookingapp.service;

import android.app.Activity;
import android.content.Context;
import android.content.Intent;
import android.content.pm.ResolveInfo;
import android.net.Uri;
import android.widget.Toast;

import androidx.appcompat.app.AlertDialog;

import com.razorpay.Checkout;
import com.sanika.bicyclebookingapp.R;
import com.sanika.bicyclebookingapp.model.Payment;
import com.sanika.bicyclebookingapp.model.PaymentConfig;
import com.sanika.bicyclebookingapp.repository.PaymentRepository;
import com.sanika.bicyclebookingapp.ui.main.MainActivity;
import com.sanika.bicyclebookingapp.util.CurrencyUtil;
import com.sanika.bicyclebookingapp.util.UpiPaymentManager;

import org.json.JSONObject;

import java.util.List;

/**
 * Service orchestrating Razorpay Standard Checkout, UPI Intent, and Sandbox Simulation.
 *
 * Implements Phase 5 Security and Business Rules:
 * - Centralizes payment initiation and order creation
 * - Initiates Razorpay checkout with Order ID generated by trusted backend
 * - Enables full Indian payment suite: UPI, UPI QR, Cards (RuPay/Visa/Mastercard), Netbanking (SBI, HDFC, ICICI, etc.), Wallets
 * - Handles UPI Intent directly if Razorpay is unavailable or on device selection
 * - Enforces server-side signature verification before acknowledging transaction success
 * - Provides safe development sandbox simulator when running in test mode without live keys
 */
public class PaymentGatewayService {

    private static volatile PaymentGatewayService instance;

    public static PaymentGatewayService getInstance() {
        if (instance == null) {
            synchronized (PaymentGatewayService.class) {
                if (instance == null) {
                    instance = new PaymentGatewayService();
                }
            }
        }
        return instance;
    }

    public interface GatewayCallback {
        void onInitiating();
        void onPaymentSuccess(String paymentId, String transactionId);
        void onPaymentFailed(String reason);
    }

    private final PaymentRepository paymentRepository;

    public PaymentGatewayService() {
        this.paymentRepository = PaymentRepository.getInstance();
    }

    /**
     * Initiates a complete real-world payment flow for a booking or invoice.
     *
     * @param activity       The calling Activity (must be MainActivity)
     * @param bookingId      Associated booking ID
     * @param invoiceId      Optional invoice ID
     * @param paymentType    "FARE" or "DEPOSIT"
     * @param customerName   Customer name for prefill
     * @param customerEmail  Customer email for prefill
     * @param customerPhone  Customer phone for prefill
     * @param callback       Result listener
     */
    public void startPayment(Activity activity,
                             String bookingId,
                             String invoiceId,
                             String paymentType,
                             String customerName,
                             String customerEmail,
                             String customerPhone,
                             GatewayCallback callback) {

        callback.onInitiating();

        // 1. Request Server-Authoritative Payment Order
        paymentRepository.createPaymentOrder(bookingId, invoiceId, paymentType, new PaymentRepository.OrderCallback() {
            @Override
            public void onSuccess(String paymentId, String orderId, long amountPaise, String keyId, boolean testMode) {
                activity.runOnUiThread(() -> {
                    // Check if live or test Razorpay key is present
                    boolean hasValidKey = keyId != null && !keyId.contains("placeholder") && !keyId.isEmpty();

                    if (hasValidKey) {
                        launchRazorpayCheckout(
                                activity, paymentId, orderId, amountPaise, keyId,
                                customerName, customerEmail, customerPhone, callback
                        );
                    } else {
                        // Safe Sandbox / UPI / Simulator Choice Dialog
                        showPaymentMethodSelectionDialog(
                                activity, paymentId, orderId, amountPaise, bookingId,
                                customerName, customerEmail, customerPhone, callback
                        );
                    }
                });
            }

            @Override
            public void onError(String message) {
                activity.runOnUiThread(() -> callback.onPaymentFailed("Failed to create order: " + message));
            }
        });
    }

    /**
     * Launches Razorpay Standard Checkout.
     */
    private void launchRazorpayCheckout(Activity activity,
                                        String paymentId,
                                        String orderId,
                                        long amountPaise,
                                        String keyId,
                                        String name,
                                        String email,
                                        String phone,
                                        GatewayCallback callback) {
        try {
            Checkout checkout = new Checkout();
            checkout.setKeyID(keyId);
            checkout.setImage(R.mipmap.ic_launcher);

            JSONObject options = new JSONObject();
            options.put("name", "CycleGo India");
            options.put("description", "Ride Payment • " + CurrencyUtil.formatInrFromPaise(amountPaise));
            options.put("currency", "INR");
            options.put("amount", amountPaise);
            if (orderId != null && !orderId.startsWith("order_test_")) {
                options.put("order_id", orderId);
            }

            // Prefill customer contact details
            JSONObject prefill = new JSONObject();
            prefill.put("name", name != null ? name : "");
            prefill.put("email", email != null ? email : "");
            prefill.put("contact", phone != null ? phone : "");
            options.put("prefill", prefill);

            // Theme branding: CycleGo Green
            JSONObject theme = new JSONObject();
            theme.put("color", "#1B5E20");
            options.put("theme", theme);

            // Wire callback into MainActivity
            if (activity instanceof MainActivity) {
                ((MainActivity) activity).setPaymentCallback(new MainActivity.PaymentCallback() {
                    @Override
                    public void onSuccess(String gatewayPaymentId) {
                        // Verify payment with server
                        verifyTransaction(paymentId, options.optString("order_id", orderId), gatewayPaymentId, null, Payment.METHOD_UPI, callback);
                    }

                    @Override
                    public void onFailure(String reason) {
                        callback.onPaymentFailed(reason);
                    }
                });
            }

            checkout.open(activity, options);

        } catch (Exception e) {
            callback.onPaymentFailed("Razorpay error: " + e.getMessage());
        }
    }

    /**
     * Method selector supporting UPI Intent, Card/Netbanking simulation, and Cash fallback.
     */
    private void showPaymentMethodSelectionDialog(Activity activity,
                                                 String paymentId,
                                                 String orderId,
                                                 long amountPaise,
                                                 String bookingId,
                                                 String name,
                                                 String email,
                                                 String phone,
                                                 GatewayCallback callback) {

        String[] methods = {
                "UPI App (GPay / PhonePe / Paytm / BHIM)",
                "Debit / Credit Card (RuPay / Visa / Mastercard - Test)",
                "Net Banking (SBI / HDFC / ICICI / Axis - Test)",
                "Pay Cash at Station"
        };

        new AlertDialog.Builder(activity)
                .setTitle("Select Payment Method (" + CurrencyUtil.formatInrFromPaise(amountPaise) + ")")
                .setItems(methods, (dialog, which) -> {
                    switch (which) {
                        case 0: // UPI
                            launchUpiIntent(activity, paymentId, orderId, amountPaise, bookingId, callback);
                            break;
                        case 1: // Card
                            simulateCardPayment(activity, paymentId, orderId, amountPaise, callback);
                            break;
                        case 2: // Netbanking
                            simulateNetbankingPayment(activity, paymentId, orderId, amountPaise, callback);
                            break;
                        case 3: // Cash
                            confirmCashPayment(activity, paymentId, orderId, bookingId, amountPaise, callback);
                            break;
                    }
                })
                .setNegativeButton("Cancel", (d, w) -> callback.onPaymentFailed("Payment cancelled by user"))
                .setCancelable(false)
                .show();
    }

    /**
     * UPI Intent invocation via Android's upi://pay URI scheme.
     */
    private void launchUpiIntent(Activity activity,
                                 String paymentId,
                                 String orderId,
                                 long amountPaise,
                                 String bookingId,
                                 GatewayCallback callback) {

        Intent upiIntent = new Intent(Intent.ACTION_VIEW, Uri.parse("upi://pay"));
        List<ResolveInfo> apps = activity.getPackageManager().queryIntentActivities(upiIntent, 0);

        if (apps != null && !apps.isEmpty()) {
            if (activity instanceof MainActivity) {
                ((MainActivity) activity).setPaymentCallback(new MainActivity.PaymentCallback() {
                    @Override
                    public void onSuccess(String txnId) {
                        verifyTransaction(paymentId, orderId, txnId, null, Payment.METHOD_UPI, callback);
                    }

                    @Override
                    public void onFailure(String reason) {
                        callback.onPaymentFailed(reason);
                    }
                });
            }

            UpiPaymentManager.startUpiPayment(
                    activity,
                    (float) CurrencyUtil.toRupees(amountPaise),
                    bookingId,
                    "CycleGo Ride Settlement"
            );
        } else {
            // No physical UPI app detected on emulator / test device -> Offer sandbox verification
            new AlertDialog.Builder(activity)
                    .setTitle("UPI Sandbox Simulation")
                    .setMessage("No Indian UPI app (Google Pay / PhonePe / Paytm) was found on this device or emulator.\n\n"
                            + "Would you like to simulate a successful UPI transaction of "
                            + CurrencyUtil.formatInrFromPaise(amountPaise) + " for testing?")
                    .setPositiveButton("Simulate UPI Payment", (dialog, which) -> {
                        String testUpiTxnId = "UPI_TEST_" + System.currentTimeMillis();
                        verifyTransaction(paymentId, orderId, testUpiTxnId, "test_sig_" + testUpiTxnId, Payment.METHOD_UPI, callback);
                    })
                    .setNegativeButton("Cancel", (d, w) -> callback.onPaymentFailed("UPI app not available"))
                    .show();
        }
    }

    /**
     * Card payment simulation for sandbox testing (Never collects or stores real PAN/CVV).
     */
    private void simulateCardPayment(Activity activity, String paymentId, String orderId, long amountPaise, GatewayCallback callback) {
        new AlertDialog.Builder(activity)
                .setTitle("Card Payment (Test Mode)")
                .setMessage("Simulating RuPay / Visa / Mastercard payment gateway for "
                        + CurrencyUtil.formatInrFromPaise(amountPaise) + ".\n\n(No actual card details collected)")
                .setPositiveButton("Authorize & Pay", (d, w) -> {
                    String cardTxnId = "CARD_TXN_" + System.currentTimeMillis();
                    verifyTransaction(paymentId, orderId, cardTxnId, "test_sig_" + cardTxnId, Payment.METHOD_DEBIT_CARD, callback);
                })
                .setNegativeButton("Cancel", (d, w) -> callback.onPaymentFailed("Card payment cancelled"))
                .show();
    }

    /**
     * Netbanking simulation for sandbox testing.
     */
    private void simulateNetbankingPayment(Activity activity, String paymentId, String orderId, long amountPaise, GatewayCallback callback) {
        String[] banks = {"State Bank of India (SBI)", "HDFC Bank", "ICICI Bank", "Axis Bank", "Punjab National Bank"};
        new AlertDialog.Builder(activity)
                .setTitle("Select Bank (Test Mode)")
                .setItems(banks, (dialog, which) -> {
                    String bankName = banks[which];
                    String nbTxnId = "NB_" + System.currentTimeMillis();
                    Toast.makeText(activity, "Redirecting from " + bankName + "...", Toast.LENGTH_SHORT).show();
                    verifyTransaction(paymentId, orderId, nbTxnId, "test_sig_" + nbTxnId, Payment.METHOD_NETBANKING, callback);
                })
                .setNegativeButton("Cancel", (d, w) -> callback.onPaymentFailed("Netbanking cancelled"))
                .show();
    }

    /**
     * Cash payment option at station.
     */
    private void confirmCashPayment(Activity activity, String paymentId, String orderId, String bookingId, long amountPaise, GatewayCallback callback) {
        new AlertDialog.Builder(activity)
                .setTitle("Cash Payment Confirmation")
                .setMessage("Please pay " + CurrencyUtil.formatInrFromPaise(amountPaise)
                        + " in cash to the station attendant.\n\nMark this booking as settled by cash?")
                .setPositiveButton("Mark as Paid", (d, w) -> {
                    String cashTxnId = "CASH_" + System.currentTimeMillis();
                    verifyTransaction(paymentId, orderId, cashTxnId, null, Payment.METHOD_CASH, callback);
                })
                .setNegativeButton("Cancel", (d, w) -> callback.onPaymentFailed("Cash payment cancelled"))
                .show();
    }

    /**
     * Verifies transaction with server-authoritative logic.
     */
    private void verifyTransaction(String paymentId,
                                   String orderId,
                                   String gatewayPaymentId,
                                   String signature,
                                   String method,
                                   GatewayCallback callback) {

        paymentRepository.verifyPayment(paymentId, paymentId, orderId, gatewayPaymentId, signature, method,
                new PaymentRepository.VerifyCallback() {
                    @Override
                    public void onSuccess(String verifiedPaymentId, String transactionId) {
                        callback.onPaymentSuccess(verifiedPaymentId, transactionId);
                    }

                    @Override
                    public void onError(String message) {
                        callback.onPaymentFailed("Verification failed: " + message);
                    }
                });
    }
}
